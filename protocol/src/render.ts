import { z } from 'zod';
import { EnvelopeBase } from './envelope.js';
import { GameFingerprint, GrantBody, LogEntry, MESSAGE_DIRECTION, MESSAGE_TYPES, ParticipantInfo, payloadSchemas } from './messages.js';
import { PROTOCOL_VERSION } from './version.js';

type JsonSchema = Record<string, unknown>;

const SHARED = {
  Envelope: EnvelopeBase,
  GameFingerprint,
  ParticipantInfo,
  GrantBody,
  LogEntry,
} as const;

function toSchema(schema: z.ZodType, id: string): JsonSchema {
  const out = z.toJSONSchema(schema, { target: 'draft-2020-12', io: 'output', unrepresentable: 'any' }) as JsonSchema;
  return { $id: `https://castcade.dev/protocol/v${PROTOCOL_VERSION}/${id}.schema.json`, ...out };
}

/** Returns { relativePath: content } for every generated file. Deterministic. */
export function renderAll(prose: string): Record<string, string> {
  const files: Record<string, string> = {};
  const schemas: Record<string, JsonSchema> = {};

  for (const [name, schema] of Object.entries(SHARED)) {
    schemas[name] = toSchema(schema, name);
    files[`schemas/${name}.schema.json`] = JSON.stringify(schemas[name], null, 2) + '\n';
  }
  for (const type of MESSAGE_TYPES) {
    schemas[type] = toSchema(payloadSchemas[type], type);
    files[`schemas/${type}.schema.json`] = JSON.stringify(schemas[type], null, 2) + '\n';
  }
  files['schemas/index.json'] =
    JSON.stringify(
      {
        protocolVersion: PROTOCOL_VERSION,
        envelope: 'Envelope.schema.json',
        shared: Object.keys(SHARED).map((n) => `${n}.schema.json`),
        messages: Object.fromEntries(MESSAGE_TYPES.map((t) => [t, { direction: MESSAGE_DIRECTION[t], schema: `${t}.schema.json` }])),
      },
      null,
      2,
    ) + '\n';
  files['SPEC.md'] = renderSpec(prose, schemas);
  return files;
}

function renderSpec(prose: string, schemas: Record<string, JsonSchema>): string {
  const lines: string[] = [];
  lines.push(`# Castcade match protocol, version ${PROTOCOL_VERSION}`);
  lines.push('');
  lines.push('<!-- GENERATED by protocol/scripts/generate.ts from protocol/src/*.ts and protocol/docs/prose.md. Do not edit. -->');
  lines.push('');
  lines.push(prose.trim());
  lines.push('');
  lines.push('## Message reference');
  lines.push('');
  lines.push('| Type | Direction | Summary |');
  lines.push('|---|---|---|');
  for (const type of MESSAGE_TYPES) {
    lines.push(`| \`${type}\` | ${MESSAGE_DIRECTION[type]} | ${oneLine(String(schemas[type]?.description ?? ''))} |`);
  }
  lines.push('');
  lines.push('### Envelope');
  lines.push('');
  lines.push(...fieldTable(schemas['Envelope']!));
  for (const type of MESSAGE_TYPES) {
    lines.push('');
    lines.push(`### \`${type}\``);
    lines.push('');
    lines.push(`Direction: ${MESSAGE_DIRECTION[type]}.`);
    lines.push('');
    lines.push(oneLine(String(schemas[type]?.description ?? '')));
    lines.push('');
    lines.push(...fieldTable(schemas[type]!));
  }
  lines.push('');
  lines.push('## Shared objects');
  for (const name of Object.keys(SHARED)) {
    if (name === 'Envelope') continue;
    lines.push('');
    lines.push(`### \`${name}\``);
    lines.push('');
    lines.push(oneLine(String(schemas[name]?.description ?? '')));
    lines.push('');
    lines.push(...fieldTable(schemas[name]!));
  }
  lines.push('');
  return lines.join('\n');
}

function fieldTable(schema: JsonSchema): string[] {
  const out: string[] = [];
  const variants = (schema['anyOf'] ?? schema['oneOf']) as JsonSchema[] | undefined;
  if (variants && !schema['properties']) {
    variants.forEach((v, i) => {
      out.push(`Variant ${i + 1}:`);
      out.push('');
      out.push(...fieldTable(v));
      out.push('');
    });
    return out;
  }
  const props = (schema['properties'] ?? {}) as Record<string, JsonSchema>;
  const required = new Set((schema['required'] as string[] | undefined) ?? []);
  if (Object.keys(props).length === 0) {
    out.push('_No fields._');
    return out;
  }
  out.push('| Field | Type | Required | Description |');
  out.push('|---|---|---|---|');
  for (const [name, p] of Object.entries(props)) {
    out.push(`| \`${name}\` | ${typeOf(p)} | ${required.has(name) ? 'yes' : 'no'} | ${oneLine(String(p['description'] ?? ''))} |`);
  }
  return out;
}

function typeOf(p: JsonSchema): string {
  if (p['const'] !== undefined) return `const \`${JSON.stringify(p['const'])}\``;
  if (Array.isArray(p['enum'])) return (p['enum'] as unknown[]).map((e) => `\`${JSON.stringify(e)}\``).join(' \\| ');
  const variants = (p['anyOf'] ?? p['oneOf']) as JsonSchema[] | undefined;
  if (variants) return variants.map(typeOf).join(' \\| ');
  const t = p['type'];
  if (Array.isArray(t)) return t.join(' \\| ');
  if (t === 'array') {
    const items = p['items'] as JsonSchema | undefined;
    return `array of ${items ? typeOf(items) : 'any'}`;
  }
  if (t === 'object') return 'object';
  if (t === 'string' && typeof p['pattern'] === 'string') return `string (\`${String(p['pattern']).replace(/\|/g, '\\|')}\`)`;
  if (t === 'number' || t === 'integer') return String(t);
  return String(t ?? 'any');
}

function oneLine(s: string): string {
  return s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}
